function addDays(isoDate: string, days: number) {
  const date = new Date(`${isoDate}T00:00:00Z`);
  date.setUTCDate(date.getUTCDate() + days);
  return date.toISOString().slice(0, 10);
}

export function activeFourWeekStart(managementStartDate: string, today = new Date()) {
  const start = new Date(`${managementStartDate}T00:00:00Z`);
  const current = Date.UTC(today.getUTCFullYear(), today.getUTCMonth(), today.getUTCDate());
  const elapsedDays = Math.max(0, Math.floor((current - start.getTime()) / 86_400_000));
  return addDays(managementStartDate, Math.floor(elapsedDays / 28) * 28);
}

export function buildFourWeekWorkPlan(): PlannedWorkItem[] {
  return [1, 2, 3, 4].flatMap((week) =>
    (WEEKLY_PLAN[week] ?? []).map(([dayOffset, title]) => ({
      week,
      dayOffset: (week - 1) * 7 + dayOffset,
      title,
    })),
  );
}

export function workPlanDate(cycleStartDate: string, item: PlannedWorkItem) {
  return addDays(cycleStartDate, item.dayOffset);
}
